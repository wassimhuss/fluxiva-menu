export type BillingCopyKey = keyof typeof arabic
export const billingText = (language: Language, key: BillingCopyKey) => language === 'ar' ? arabic[key] : key
export function billingError(language: Language, error: unknown) {
  const message = error instanceof Error ? error.message : typeof error === 'object' && error && 'message' in error ? String(error.message) : ''
  return billingText(language, message in arabic ? message as BillingCopyKey : 'Request failed. Please refresh and try again.')
}
