  await scalar('select public.owner_read_notification($1) as value',[id])
  assert.equal((await feed()).messages[0].read_at,readAt);assert.equal((await feed()).unread_count,0)
  await asUser(ids.other);assert.equal((await feed()).unread_count,1) // Reading one account never reads another account's copy.
  await db.exec('reset role')
  const late=crypto.randomUUID();await db.query("insert into auth.users(id,email) values($1,'alerts-late@example.com')",[late])
  await asUser(late);assert.equal((await feed()).total,0)
  await assert.rejects(scalar('select public.owner_read_notification($1) as value',[id]),/unavailable/)
  await asUser(ids.admin);assert.deepEqual(await send(),receipt) // Retrying does not add late recipients.
  assert.equal((await history()).messages[0].read_count,1)
  await db.exec('reset role')
  await db.exec("create function private.fail_announcement_audit() returns trigger language plpgsql as $$begin if new.action='announcement.sent' then raise exception 'audit unavailable'; end if; return new; end$$; create trigger fail_announcement_audit before insert on private.platform_audit_log for each row execute function private.fail_announcement_audit();")
  const failed=crypto.randomUUID()
  await asUser(ids.admin);await assert.rejects(send(failed),/audit unavailable/)
  await db.exec('reset role')
  assert.equal(await scalar('select count(*) as value from private.platform_announcements where id=$1',[failed]),0)
  assert.equal(await scalar('select count(*) as value from private.owner_notifications where announcement_id=$1',[failed]),0)
