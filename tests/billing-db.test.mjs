  const send=(request=id,draft=input)=>scalar('select public.platform_send_announcement($1,$2) as value',[request,draft])
  const feed=(page=0)=>scalar('select public.owner_notifications($1) as value',[page])
  const history=(page=0)=>scalar('select public.platform_list_announcements($1) as value',[page])
  for(const user of [ids.owner,ids.other,ids.empty]) {
    await asUser(user); await assert.rejects(send(),/Platform access/); await assert.rejects(history(),/Platform access/)
    await assert.rejects(scalar('select * from private.platform_announcements'),/permission denied/)
    await assert.rejects(scalar('select * from private.owner_notifications'),/permission denied/)
  }
  await asUser(ids.support); await assert.rejects(send(),/Super admin/)
  await assert.rejects(feed(),/Owner access/)
  await asUser(null,'anon')
  await assert.rejects(send(),/permission denied/); await assert.rejects(feed(),/permission denied/)
  await assert.rejects(history(),/permission denied/)
  await assert.rejects(scalar('select public.owner_read_notification($1) as value',[id]),/permission denied/)
  await asUser(ids.admin)
  for(const draft of [null,{},[],{...input,title_ar:''},{...input,body_en:' '},{...input,title_en:'a'.repeat(201)},{...input,body_ar:'a'.repeat(5001)}]) await assert.rejects(send(crypto.randomUUID(),draft),/both titles/)
  const receipt=await send()
  assert.equal(receipt.id,id);assert.equal(receipt.recipient_count,4) // Includes owners without restaurants; excludes both operator roles.
  assert.deepEqual(await send(),receipt)
  await assert.rejects(send(id,{...input,body_en:'Different'}),/already used/)
  assert.equal((await history()).total,1)
  await asUser(ids.support);assert.equal((await history()).messages[0].recipient_count,4)
  await asUser(ids.owner)
  const first=await feed();assert.equal(first.unread_count,1);assert.equal(first.total,1)
  assert.deepEqual(Object.keys(first.messages[0]).sort(),['id','title_en','title_ar','body_en','body_ar','created_at','read_at'].sort())
  assert.equal(first.messages[0].body_ar,input.body_ar)
